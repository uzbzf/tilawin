export const verseList = Object.values(moodPools).flat()

/** @deprecated flat map kept for search compatibility */
export const verses = Object.fromEntries(verseList.map((v) => [v.id, v]))

export function pickRandomVerse(moodId, excludeId) {
  const pool = moodPools[moodId] || []
  if (!pool.length) return null
  if (pool.length === 1) return pool[0]
  const options = excludeId ? pool.filter((v) => v.id !== excludeId) : pool
  return options[Math.floor(Math.random() * options.length)] || pool[0]
}

export function searchVerses(query, lang = 'ru') {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return verseList.filter((verse) => {
    const hay = [
      verse.ref,
      verse.arabic,
      verse.text.ru,
      verse.text.uz,
      verse.text.en,
      verse.surah.ru,
      verse.surah.uz,
      verse.surah.en,
      ...(verse.keywords || []),
      verse.text[lang],
      verse.surah[lang],
      verse.translator,
    ]
      .join(' ')
      .toLowerCase()
    return hay.includes(q)
  })
}
